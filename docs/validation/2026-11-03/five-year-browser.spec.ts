import { readFileSync } from "node:fs";
import { test, expect, collectPageErrors } from "./fixtures";
const record = JSON.parse(readFileSync("five-year-data/validation.json", "utf8"));
test("five-year history renders, survives reload, and opens the next year", async ({ page, context, baseURL }, testInfo) => {
 test.setTimeout(180_000);
 const errors: string[] = [];
 collectPageErrors(page, baseURL!, errors);
 await context.addCookies([{ name: "orbital_save", value: record.id, url: baseURL! }]);
 await page.goto("/result?analytics-test=1");
 await expect(page.getByRole("heading", { name: "Q4 2198: the results" })).toBeVisible();
 const history = page.getByRole("region", { name: "Service record" });
 await expect(history.getByRole("row")).toHaveCount(21);
 await expect(history.getByRole("row", { name: /^Q1 2194/ })).toBeVisible();
 await expect(history.getByRole("row", { name: /^Q4 2198/ })).toBeVisible();
 await page.screenshot({ path: testInfo.outputPath("five-year-result.png"), fullPage: true });
 await page.waitForLoadState("networkidle");
 await page.reload();
 await expect(history.getByRole("row")).toHaveCount(21);
 await page.waitForLoadState("networkidle");
 await page.goto("/result?analytics-test=1&quarter=2194-Q1");
 await expect(page.getByRole("heading", { name: "Q1 2194: the results" })).toBeVisible();
 await page.waitForLoadState("networkidle");
 await page.goto("/investigate?analytics-test=1&measure=revenue&by=quarter");
 await expect(page.getByRole("link", { name: "Write the plan" })).toBeVisible();
 await page.waitForLoadState("networkidle");
 await page.screenshot({ path: testInfo.outputPath("five-year-investigate.png"), fullPage: true });
 await page.goto("/reports?analytics-test=1");
 await expect(page.getByRole("region", { name: "Service record" }).getByRole("row")).toHaveCount(21);
 await page.waitForLoadState("networkidle");
 await page.goto("/decide?analytics-test=1");
 await expect(page.getByRole("heading", { name: "PLAN FOR Q1 2199" })).toBeVisible({ timeout: 60_000 });
 await page.waitForLoadState("networkidle");
 await page.screenshot({ path: testInfo.outputPath("next-year-decide.png"), fullPage: true });
 expect(errors).toEqual([]);
});
